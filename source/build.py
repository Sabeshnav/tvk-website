"""Builds the whole TVK concept site into one self-contained file: dist/index.html.

Each section keeps its own sources in src/sections/<name>/ (main.js + page.html + scene modules).
This script:
  1. wraps every section's main.js in `export function start(requestAnimationFrame)` (src/sections/<name>/_entry.js),
     so the shell can start sections lazily and run their animation loops only near the screen;
  2. takes each page.html's markup (minus the stand-alone spacers) and scopes its CSS to the section
     (selectors prefixed with #c-<name>, :root -> the section, keyframes renamed, html/body and @font-face dropped);
  3. bundles src/shell.js with esbuild (three 0.185.1 from node_modules) and inlines fonts and images as base64.
Needs: node_modules with three@0.185.1, three-bvh-csg, three-mesh-bvh and esbuild.
"""
import base64, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(ROOT, 'src')
SECTIONS = ['hero', 'leader', 'kural', 'pledge', 'journey', 'join']


def rd(p): return open(os.path.join(ROOT, p), encoding='utf-8').read()
def b64(p): return base64.b64encode(open(os.path.join(ROOT, p), 'rb').read()).decode()


# ---------------- 1. section entry wrappers ----------------
for s in SECTIONS:
    src = rd(f'src/sections/{s}/main.js').split('\n')
    k = 0
    while k < len(src) and (src[k].startswith('import ') or src[k].startswith('//') or not src[k].strip()): k += 1
    imports, body = src[:k], src[k:]
    out = '// generated by build.py: do not edit\n' + '\n'.join(imports) + '\nexport function start(requestAnimationFrame) {\n' + '\n'.join(body) + '\n}\n'
    open(os.path.join(SRC, 'sections', s, '_entry.js'), 'w', encoding='utf-8').write(out)


# ---------------- 2. CSS scoping ----------------
def parse(css):
    """Split a stylesheet into [(prelude, body_or_None)] at the top level, skipping comments and strings."""
    out, i, n, start = [], 0, len(css), 0
    while i < n:
        c = css[i]
        if css.startswith('/*', i): i = css.index('*/', i) + 2; continue
        if c in '"\'':
            j = i + 1
            while css[j] != c: j += 2 if css[j] == '\\' else 1
            i = j + 1; continue
        if c == ';' and re.sub(r'/\*.*?\*/', '', css[start:i], flags=re.S).strip().startswith('@'):
            out.append((css[start:i].strip(), None)); i += 1; start = i; continue
        if c == '{':
            depth, j = 1, i + 1
            while depth:
                if css.startswith('/*', j): j = css.index('*/', j) + 2; continue
                if css[j] in '"\'':
                    q = css[j]; j += 1
                    while css[j] != q: j += 2 if css[j] == '\\' else 1
                if css[j] == '{': depth += 1
                elif css[j] == '}': depth -= 1
                j += 1
            pre = re.sub(r'/\*.*?\*/', '', css[start:i], flags=re.S).strip()
            out.append((pre, css[i + 1:j - 1])); i = j; start = i; continue
        i += 1
    return out


def split_sel(sel):
    parts, depth, cur = [], 0, ''
    for ch in sel:
        if ch in '([': depth += 1
        elif ch in ')]': depth -= 1
        if ch == ',' and depth == 0: parts.append(cur); cur = ''
        else: cur += ch
    parts.append(cur)
    return [p.strip() for p in parts if p.strip()]


def scope_css(css, sec):
    scope = f'#c-{sec}'
    frames = {}
    def walk(css):
        res = []
        for pre, body in parse(css):
            if body is None: continue
            if pre.startswith('@font-face'): continue
            if pre.startswith('@keyframes'):
                name = pre.split()[1]; frames[name] = f'{sec}-{name}'
                res.append(f'@keyframes {sec}-{name}{{{body}}}'); continue
            if pre.startswith('@media') or pre.startswith('@supports'):
                inner = walk(body)
                if inner.strip(): res.append(f'{pre}{{{inner}}}')
                continue
            sels = []
            for p in split_sel(pre):
                if p.startswith(':root'): sels.append(scope + p[5:])
                elif re.match(r'^(html|body)\b', p): continue
                else: sels.append(f'{scope} {p}')
            if sels: res.append(','.join(sels) + '{' + body.strip() + '}')
        return '\n'.join(res)
    out = walk(css)
    def ren(m):
        v = m.group(2)
        for a, b in frames.items(): v = re.sub(r'(?<![\w-])' + re.escape(a) + r'(?![\w-])', b, v)
        return m.group(1) + v
    return re.sub(r'(animation(?:-name)?\s*:)([^;}]*)', ren, out)


markup, css_all = {}, []
for s in SECTIONS:
    page = rd(f'src/sections/{s}/page.html')
    css = re.search(r'<style>(.*?)</style>', page, re.S).group(1)
    body = page[page.index('</style>') + 8:]
    body = re.sub(r'<script>.*?</script>', '', body, flags=re.S)
    body = re.sub(r'<div class="spacer">.*?</div>', '', body, flags=re.S)
    body = re.sub(r'<section class="next"[^>]*>.*?</section>', '', body, flags=re.S)
    markup[s] = body.strip()
    css_all.append(f'/* ---- {s} ---- */\n' + scope_css(css, s))


# ---------------- 3. fonts ----------------
LATIN = 'U+0000-00FF,U+2013-2014,U+2018-201D,U+00B7,U+2026,U+20B9,U+2190-2193'
TAMIL = 'U+0B80-0BFF,U+200C-200D,U+25CC'
def face(fam, w, f, rng=None):
    r = f';unicode-range:{rng}' if rng else ''
    return f'@font-face{{font-family:"{fam}";font-weight:{w};font-display:swap;src:url(data:font/woff2;base64,{b64("fonts/" + f)}) format("woff2"){r}}}'
fonts = '\n'.join([
    face('Archivo', 600, 'archivo-latin-600-normal.woff2', LATIN), face('Archivo', 800, 'archivo-latin-800-normal.woff2', LATIN), face('Archivo', 900, 'archivo-latin-900-normal.woff2', LATIN),
    face('Catamaran', 800, 'catamaran-latin-800-normal.woff2', LATIN), face('Catamaran', 900, 'catamaran-latin-900-normal.woff2', LATIN),
    face('Catamaran', 800, 'catamaran-tamil-800-normal.woff2', TAMIL), face('Catamaran', 900, 'catamaran-tamil-900-normal.woff2', TAMIL),
    face('Cinzel', 500, 'cinzel-latin-500-normal.woff2'), face('Cinzel', 700, 'cinzel-latin-700-normal.woff2'),
    face('TamilSerif', 400, 'noto-serif-tamil-tamil-400-normal.woff2', TAMIL), face('TamilSerif', 700, 'noto-serif-tamil-tamil-700-normal.woff2', TAMIL),
    face('TamilSerif', 400, 'noto-serif-tamil-latin-400-normal.woff2', LATIN),
])

# ---------------- 4. bundle ----------------
os.makedirs(os.path.join(ROOT, 'dist'), exist_ok=True)
r = subprocess.run(['npx', 'esbuild', 'src/shell.js', '--bundle', '--minify', '--format=iife', '--target=es2020', '--legal-comments=none',
                    '--outfile=dist/bundle.js', '--log-level=warning'], cwd=ROOT)
if r.returncode: sys.exit(1)
js = rd('dist/bundle.js')

subs = {
    '__NST700_B64__': b64('fonts/noto-serif-tamil-tamil-700-normal.woff2'),
    '__CINZEL700_B64__': b64('fonts/cinzel-latin-700-normal.woff2'),
    '__KAVIVANAR_B64__': b64('fonts/kavivanar-tamil-400-normal.woff2'),
    '__FLAG_B64__': b64('src/sections/hero/flag.webp'),
    '__START_B64__': b64('src/sections/leader/leader-start.webp'),
    '__END_B64__': b64('src/sections/leader/leader-end.webp'),
    '__AADHAV_B64__': b64('src/sections/leader/aadhav.webp'),
    '__ANAND_B64__': b64('src/sections/leader/anand.webp'),
}
for k, v in subs.items(): js = js.replace(k, v)

page = rd('src/shell.html')
page = page.replace('/*FONTS*/', fonts).replace('/*SECTION_CSS*/', '\n'.join(css_all))
for s in SECTIONS: page = page.replace(f'<!--SEC:{s}-->', markup[s])
for k, v in subs.items(): page = page.replace(k, v)
page = page.replace('/*INLINE_JS*/', js.replace('</script', '<\\/script'))

left = set(re.findall(r'__[A-Z0-9]+_B64__', page))
if left: sys.exit(f'unfilled placeholders: {left}')
ids = re.findall(r'\sid="([^"]+)"', re.sub(r'<script>.*?</script>', '', page, flags=re.S))
dup = {i for i in ids if ids.count(i) > 1}
if dup: sys.exit(f'duplicate ids: {dup}')
open(os.path.join(ROOT, 'dist', 'index.html'), 'w', encoding='utf-8').write(page)
# the GitHub Pages copy at the repository root
open(os.path.join(ROOT, '..', 'index.html'), 'w', encoding='utf-8').write(page)
os.remove(os.path.join(ROOT, 'dist', 'bundle.js'))
print('built dist/index.html', len(page.encode()) // 1024, 'KB')
